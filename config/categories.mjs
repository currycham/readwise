export function categoryListText() {
  // 名称和说明分开写，避免模型把说明当成名称的一部分抄进 sub
  const list = CATEGORIES.map(c => `大问题：${c.name}\n${c.subs.map(s => `  子问题：${s}　　（收：${c.desc[s]}）`).join('\n')}`).join('\n');
  return `${list}\n\ntop 和 sub 只填“大问题：”“子问题：”后面的名称本身，不要带括号里的说明。\n\n归类规则：\n${CATEGORY_RULES.map(r => `- ${r}`).join('\n')}`;
}

/** 去掉模型偶尔附带在名称后面的说明，如“想改变习惯：建立好习惯……”“想改变习惯（收：……）” */
export const cleanCategoryName = s => String(s || '').split(/[：:（(]/)[0].trim();

export function isValidCategory(top, sub) {
  const c = CATEGORIES.find(x => x.name === top);
  return !!c && c.subs.includes(sub);
}

/** 把可能是旧名的分类换成当前分类；换不了返回 null */
export function normalizeCategory(cat) {
  if (!cat) return null;
  const top = cleanCategoryName(cat.top), sub = cleanCategoryName(cat.sub);
  if (isValidCategory(top, sub)) return { top, sub };
  const to = RENAMES[`${top}/${sub}`];
  if (!to) return null;
  const [t, u] = to.split('/');
  return { top: t, sub: u };
}
